用日常语言解释想法、情绪、期待、恐惧、控制、界限和行动；具体生活例子必须标为可能情境，不编造观众的婚姻、童年或工作经历。分清“你以为的状态”与“目前可以核实的事实”。语气有同理心，但不急着替对方下结论。

