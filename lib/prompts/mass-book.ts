export function buildMassBookUserPrompt(theme: MassTheme, group: number, symbol: string, question: string, verificationCards: CardInfo[], readingCards: CardInfo[]): string {
  const list = (cards: CardInfo[]) => cards.map((c,i) => `第${i+1}张：${c.nameZh}（${c.name}）— ${c.isReversed ? "逆位" : "正位"}`).join("\n");
  return `大众占卜，主题「${THEME_LABELS[theme]}」，观众第${group}组（${symbol}）。\n问题：${JSON.stringify(question)}\n【验证牌 · 3张】\n${list(verificationCards)}\n【解读牌 · 5张】\n${list(readingCards)}\n按案例讲解人格的五节结构输出，保留验证牌与解读牌各自用途；结合实际问题循序解释牌间联系。`;
}
