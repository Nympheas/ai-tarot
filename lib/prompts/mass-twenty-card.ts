export function isTwentyCardReading(cards: unknown): cards is CardInfo[] {
  return Array.isArray(cards) && cards.length === 20 && cards.every(c => c && typeof c === "object" && typeof c.name === "string" && !!c.name.trim() && typeof c.nameZh === "string" && !!c.nameZh.trim() && typeof c.isReversed === "boolean") && new Set(cards.map(c => c.name)).size === 20 && new Set(cards.map(c => c.nameZh)).size === 20;
}
