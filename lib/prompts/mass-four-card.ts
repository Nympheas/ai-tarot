export function isFourCardReading(cards: unknown): cards is CardInfo[] {
  return Array.isArray(cards) && cards.length === 4 && cards.every((card) =>
    card !== null && typeof card === "object" &&
    typeof card.nameZh === "string" && card.nameZh.trim().length > 0 &&
    typeof card.name === "string" && card.name.trim().length > 0 &&
    typeof card.isReversed === "boolean"
  );
}

export function withFourCardSpread(basePrompt: string, personality: MassPersonality): string {
  const cases = FOUR_CARD_CASES.map((example, index) =>
    `案例${index + 1}：${example.title}（书内页${example.pages}）\n` +
    example.cards.map((card, i) => `${FOUR_CARD_POSITIONS[i]}＝${card}`).join("；") +
    `。\n${"clarifiers" in example ? `教材补充：${example.clarifiers}\n` : ""}${example.lesson}`
  ).join("\n\n");

  return `${basePrompt}

## 本次抽牌方式：四张牌关系解读法
本次沿用上述选定人格、语气、称呼、禁词、表达节奏及收尾风格。以下仅替换牌数、牌位和输出结构。每组只抽四张牌，不含验证牌，不输出星座、信息对应、特定讯息，不自行加牌。
方法参考钟适惠《塔罗教室，就在你家》书内页37–39；案例参考书内页82–101。用于理解伴侣、家人、朋友、同事、主管等关系。

牌位由左到右固定为：
1. 头脑：抽牌者对这段关系的自觉感受、期待、担忧，以及对关系人的看法。区分主观看法和已经确认的事实。
2. 忠告：抽牌者在关系中需要看见或觉察的部分；可作为头脑牌的补充，提醒其未察觉的盲点。
3. 结果：接受忠告、采取建议后的可能结果，或看清处境后需要采取的行动；不是必然命运，也不一定是事件预测。
4. 关系人：关系对象在双方互动中可能呈现的情感、思绪或状态，有时也反映对方个人的一般状态。不能把它当作读取对方隐私、真实想法或是否出轨的证据。

读牌顺序：先读前三张抽牌者的牌，理解头脑→忠告→结果的联系；最后单独读第四张关系人的牌。第四张独立于前三张，不能混成一个人的四阶段故事，也不是第三张之后的最终结果。可以对照双方的差异，提供协调和沟通的观察方向，不能把双方情绪混为一谈。以「关于我与对方的关系，我应有什么了解」为分析视角，仍需回答用户的具体问题。
根据用户问题确定关系人是谁，不固定为恋人；涉及多个人且对象不清时，说明不确定，不擅自认定。问题没有明确关系对象时，也不要编造伴侣或第三者。

以下10个教材案例是方法参考，牌名、牌位及补充牌保持教材区别。案例不是本次抽牌，不是当前观众的经历；不要把教材的补充牌塞进本次四张牌。教材未注明正逆位，不替案例臆造逆位；本次输入若有正逆位，须按实际输入解释。
${cases}

牌名说明：书中金币也称星币；奢华＝圣杯四，失望＝圣杯五，英勇＝权杖七，忧伤＝宝剑三，成功＝金币六，主权＝权杖二，挫败＝宝剑五，怠惰＝圣杯八，内在的力量＝权杖九，欢乐＝圣杯六，争吵＝权杖五，工作＝金币三，休战＝宝剑四，担忧＝金币五，美德＝权杖三。艺术、调整、爱人、死亡是书中的透特牌名，可按牌名识别与当前牌库的节制、正义、恋人、死神的对应主题；不凭不同牌系的编号硬套。保留教材王子、公主、骑士的区别，不因名称相近就混同。案例中的具体含义随问题和位置变化，不是固定牌义。

本次直接用以下四个章节输出，每节写明实际抽到的牌名及正逆位：
### 🧠 头脑
### 💡 忠告
### 🌙 结果
### 🤝 关系人
${personality === "intp"
    ? "保持原有 INTP 的疲惫、观察与拆本质表达。前三张的联系自然融入观察，第四张单独看对方。不要增加报告式总结、祝福、鸡汤或强行圆满，不使用原人格禁止的词。"
    : "保持默认人格的口头禅、称呼、分层解读及生活化举例。前三张自然衔接，第四张从对方在互动中的状态切入，结尾沿用温暖建议和祝福。"}
保持所选人格原来的字数要求。案例用来学习方法，不要求在结果中逐个复述；只围绕本期问题和实际四张牌解读。`;
}

export function buildFourCardUserPrompt(
  theme: MassTheme, groupNumber: number, groupSymbol: string,
  question: string, cards: CardInfo[]
): string {
  const list = cards.map((card, i) =>
    `第${i + 1}张 · ${FOUR_CARD_POSITIONS[i]}：${card.nameZh}（${card.name}）— ${card.isReversed ? "逆位" : "正位"}`
  ).join("\n");
  return `大众占卜，主题「${THEME_LABELS[theme]}」，第${groupNumber}组（${groupSymbol}）。
本期问题：${JSON.stringify(question)}
【四张牌关系解读法】
${list}
请保持选定人格，先读前三张抽牌者的牌，再单独读第四张关系人的状态，不将第四张混入前三张的个人发展过程。`;
}

